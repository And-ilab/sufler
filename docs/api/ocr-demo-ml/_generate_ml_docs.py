NAVY = (15, 23, 71)
BG = (244, 247, 252)
CARD = (255, 255, 255)
LINE = (20, 32, 90)
MUTED = (90, 98, 120)
INK = (18, 22, 38)


def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    windir = Path(os.environ.get("WINDIR", "C:/Windows"))
    names = (
        ["arialbd.ttf", "segoeuib.ttf", "calibrib.ttf"]
        if bold
        else ["arial.ttf", "segoeui.ttf", "calibri.ttf"]
    )
    for name in names:
        path = windir / "Fonts" / name
        if path.is_file():
            return ImageFont.truetype(str(path), size)
    return ImageFont.load_default()


def rounded(draw: ImageDraw.ImageDraw, box: tuple[int, int, int, int]) -> None:
    draw.rounded_rectangle(box, radius=18, fill=CARD, outline=LINE, width=2)


def draw_doc(title: str, subtitle: str, fields: list[tuple[str, str]], extra: list[str]) -> Image.Image:
    width, height = 1400, 2400
    img = Image.new("RGB", (width, height), BG)
    draw = ImageDraw.Draw(img)
    draw.rectangle((0, 0, width, 150), fill=NAVY)
    draw.text((48, 36), title.upper(), font=font(42, True), fill=CARD)
    draw.text((48, 96), subtitle, font=font(22), fill=(190, 198, 220))

    y = 190
    for i in range(0, len(fields), 2):
        pair = fields[i : i + 2]
        if len(pair) == 2:
            boxes = [(48, y, 676, y + 150), (724, y, 1352, y + 150)]
        else:
            boxes = [(48, y, 1352, y + 150)]
        for (label, value), box in zip(pair, boxes):
            rounded(draw, box)
            draw.text((box[0] + 28, box[1] + 22), label, font=font(20), fill=MUTED)
            draw.text((box[0] + 28, box[1] + 68), value, font=font(30, True), fill=INK)
        y += 174

    rounded(draw, (48, y, 1352, height - 48))
    draw.text((76, y + 24), "Дополнительно / примечания", font=font(20), fill=MUTED)
    ty = y + 70
    for line in extra:
        draw.text((76, ty), line, font=font(24), fill=INK)
        ty += 40
    return img


